import { getMigrations } from "better-auth/db/migration";
import { auth } from "../src/lib/auth";
import { migrateCredits } from "../src/lib/credits";
import { bootstrapAdmin } from "../src/lib/admin";
import { db } from "../src/lib/db";

try {
  const { toBeCreated, toBeAdded, runMigrations } = await getMigrations(auth.options);
  if (toBeCreated.length || toBeAdded.length) await runMigrations();
  const connection = await db.getConnection();
  try {
    await connection.beginTransaction();
    await connection.execute("SELECT pg_advisory_xact_lock(1835462101)");
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "userProfile" (
        "userId" TEXT NOT NULL PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
        "dateOfBirth" DATE CHECK ("dateOfBirth" >= DATE '1900-01-01'),
        sex TEXT CHECK (sex IN ('female', 'male', 'intersex', 'prefer_not_to_say')),
        "updatedAt" TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
      )
    `);
    await connection.execute(`ALTER TABLE "userProfile" ADD COLUMN IF NOT EXISTS "avatarId" TEXT
      CHECK ("avatarId" IN ('apple', 'sprout', 'cat', 'bear', 'bunny', 'panda'))`);
    await connection.execute(`ALTER TABLE "userProfile" ADD COLUMN IF NOT EXISTS "heightCm" NUMERIC(4,1)
      CHECK ("heightCm" > 0 AND "heightCm" <= 300)`);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodGoal" (
        "userId" TEXT NOT NULL PRIMARY KEY REFERENCES "user"(id) ON DELETE CASCADE,
        targets JSONB NOT NULL CHECK (jsonb_typeof(targets) = 'object'),
        "updatedAt" TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
      )
    `);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodGoalVersion" (
        "userId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
        "effectiveFrom" DATE NOT NULL CHECK ("effectiveFrom" BETWEEN DATE '2000-01-01' AND DATE '2100-12-31'),
        targets JSONB NOT NULL CHECK (jsonb_typeof(targets) = 'object'),
        "updatedAt" TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        PRIMARY KEY ("userId", "effectiveFrom")
      )
    `);
    // Earlier versions were never recorded. Preserve only the latest known save date (UTC).
    await connection.execute(`INSERT INTO "foodGoalVersion" ("userId", "effectiveFrom", targets, "updatedAt")
      SELECT g."userId", g."updatedAt"::date, g.targets, g."updatedAt" FROM "foodGoal" g
      WHERE NOT EXISTS (SELECT 1 FROM "foodGoalVersion" v WHERE v."userId" = g."userId")
      ON CONFLICT ("userId", "effectiveFrom") DO NOTHING`);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodAiBudget" (
        scope VARCHAR(64) NOT NULL, month CHAR(7) NOT NULL,
        "usedMicros" BIGINT NOT NULL DEFAULT 0 CHECK ("usedMicros" >= 0),
        PRIMARY KEY (scope, month)
      )
    `);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodAiUsage" (
        id TEXT NOT NULL PRIMARY KEY, scope VARCHAR(64) NOT NULL, "budgetMonth" CHAR(7) NOT NULL,
        "userId" TEXT REFERENCES "user"(id) ON DELETE SET NULL,
        "imageHash" CHAR(64) NOT NULL,
        status TEXT NOT NULL CHECK (status IN ('pending','succeeded','rejected','failed')),
        "costMicros" BIGINT NOT NULL CHECK ("costMicros" >= 0),
        "promptTokens" INTEGER, "outputTokens" INTEGER,
        "resultJson" JSONB, "cacheExpiresAt" TIMESTAMP, "createdAt" TIMESTAMP NOT NULL,
        FOREIGN KEY (scope, "budgetMonth") REFERENCES "foodAiBudget"(scope, month)
      )
    `);
    await migrateCredits(connection);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodChat" (
        id TEXT NOT NULL PRIMARY KEY, "userId" TEXT NOT NULL UNIQUE REFERENCES "user"(id) ON DELETE CASCADE,
        version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0), "draftJson" JSONB,
        "pendingRequestId" TEXT, "pendingToken" TEXT, "pendingStartedAt" TIMESTAMP
      )
    `);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodChatMessage" (
        id TEXT NOT NULL PRIMARY KEY, sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
        "chatId" TEXT NOT NULL REFERENCES "foodChat"(id) ON DELETE CASCADE,
        "requestId" TEXT NOT NULL, role TEXT NOT NULL CHECK (role IN ('user','assistant')),
        content TEXT NOT NULL, payload JSONB NOT NULL, "createdAt" TIMESTAMP NOT NULL,
        UNIQUE ("chatId", "requestId", role)
      )
    `);
    await connection.execute(`
      CREATE TABLE IF NOT EXISTS "foodEntry" (
        id TEXT NOT NULL PRIMARY KEY, "userId" TEXT NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
        name VARCHAR(120) NOT NULL,
        calories NUMERIC(8,2) NOT NULL CHECK (calories >= 0),
        protein NUMERIC(7,2) NOT NULL CHECK (protein >= 0),
        carbs NUMERIC(7,2) NOT NULL CHECK (carbs >= 0),
        fat NUMERIC(7,2) NOT NULL CHECK (fat >= 0),
        meal TEXT CHECK (meal IN ('breakfast','lunch','dinner','snack')),
        category TEXT NOT NULL DEFAULT 'healthy' CHECK (category IN ('healthy','unhealthy')),
        "eatenAtLocal" TIMESTAMP NOT NULL, "timeZone" VARCHAR(64) NOT NULL,
        "analysisId" TEXT REFERENCES "foodAiUsage"(id) ON DELETE SET NULL,
        "chatMessageId" TEXT REFERENCES "foodChatMessage"(id) ON DELETE SET NULL,
        "createdAt" TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
        "updatedAt" TIMESTAMP NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
      )
    `);
    for (const sql of [
      'CREATE INDEX IF NOT EXISTS food_owner_date ON "foodEntry" ("userId", "eatenAtLocal")',
      'CREATE INDEX IF NOT EXISTS ai_scope_date ON "foodAiUsage" (scope, "createdAt")',
      'CREATE INDEX IF NOT EXISTS ai_user_photo ON "foodAiUsage" (scope, "userId", "imageHash", "createdAt")',
      'CREATE INDEX IF NOT EXISTS ai_cache_expiry ON "foodAiUsage" ("cacheExpiresAt")',
      'CREATE INDEX IF NOT EXISTS chat_history ON "foodChatMessage" ("chatId", sequence)',
    ]) await connection.execute(sql);
    await connection.execute(`CREATE OR REPLACE FUNCTION daywell_food_updated_at() RETURNS TRIGGER AS $$
      BEGIN NEW."updatedAt" = (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'); RETURN NEW; END;
      $$ LANGUAGE plpgsql`);
    await connection.execute('DROP TRIGGER IF EXISTS daywell_food_updated_at ON "foodEntry"');
    await connection.execute('CREATE TRIGGER daywell_food_updated_at BEFORE UPDATE ON "foodEntry" FOR EACH ROW EXECUTE FUNCTION daywell_food_updated_at()');
    await connection.commit();
  } catch (error) { await connection.rollback(); throw error; }
  finally { connection.release(); }
  const bootstrap = await bootstrapAdmin(process.env);
  if (bootstrap === "promoted") console.log("Existing account granted administrator access. Sign in at /admin with its usual password.");
  console.log("Postgres authentication, profiles, food journal, daily goals, AI budget, credits, and chat schemas are ready.");
} catch (error) {
  console.error("Could not migrate Postgres. Check DATABASE_URL and database connectivity.");
  if (error && typeof error === "object" && "code" in error) console.error("Database error code:", String(error.code));
  process.exitCode = 1;
} finally { await db.end(); }
